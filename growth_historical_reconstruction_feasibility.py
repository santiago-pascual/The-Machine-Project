def dependency_audit() -> pd.DataFrame:
    out = pd.DataFrame(_component_rows())
    out.to_csv(OUT_DEPENDENCY, index=False)
    return out


def reconstructability(dependencies: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, row in dependencies.iterrows():
        component = row["component"]
        label = str(row["reconstructability"])
        if label.startswith("fully"):
            classification = "fully_reconstructable"
        elif label.startswith("partially") or "if full model pipeline" in label:
            classification = "partially_reconstructable"
        elif "not required" in label:
            classification = "not_required_for_growth_v2"
        else:
            classification = "not_reconstructable"
        rows.append(
            {
                "component": component,
                "classification": classification,
                "can_reconstruct_exact_pre_2022": bool(classification == "fully_reconstructable" and component in {"exposure_cap_60"}),
                "can_reconstruct_approx_pre_2022": bool(classification in {"fully_reconstructable", "partially_reconstructable"}),
                "price_only_possible": bool(component in {"volatility_target_22pct", "exposure_cap_60"}),
                "blocking_issue": "" if classification != "not_reconstructable" else "requires model-generated target snapshots or full historical pipeline replay",
                "notes": row.get("notes", ""),
            }
        )
    out = pd.DataFrame(rows)
    out.to_csv(OUT_RECONSTRUCT, index=False)
    return out


def historical_data_coverage() -> pd.DataFrame:
    snapshots = _dates(_read_csv(SNAPSHOTS_FILE))
    realized = _dates(_read_csv(REALIZED_FILE))
    trades = _dates(_read_csv(GROWTH_TRADES_FILE))
    if trades.empty or "ticker" not in trades.columns:
        tickers = sorted(snapshots["ticker"].dropna().astype(str).unique()) if "ticker" in snapshots.columns else []
    else:
        tickers = sorted(trades["ticker"].dropna().astype(str).unique())

    rows = []
    for ticker in tickers:
        snap_t = snapshots[snapshots.get("ticker", pd.Series(dtype=str)).astype(str).eq(ticker)].copy() if not snapshots.empty else pd.DataFrame()
        real_t = realized[realized.get("ticker", pd.Series(dtype=str)).astype(str).eq(ticker)].copy() if not realized.empty else pd.DataFrame()
        all_dates = snap_t["date"] if not snap_t.empty else pd.Series(dtype="datetime64[ns]")
        first_date = all_dates.min() if not all_dates.empty else pd.NaT
        last_date = all_dates.max() if not all_dates.empty else pd.NaT
        obs = int(len(all_dates))
        expected_obs = int(snapshots["date"].nunique()) if not snapshots.empty and "date" in snapshots.columns else obs
        missing_pct = float(max(0, expected_obs - obs) / expected_obs) if expected_obs else np.nan
        rows.append(
            {
                "ticker": ticker,
                "first_available_snapshot_date": first_date.strftime("%Y-%m-%d") if pd.notna(first_date) else "",
                "last_available_snapshot_date": last_date.strftime("%Y-%m-%d") if pd.notna(last_date) else "",
                "snapshot_observations": obs,
                "realized_return_observations": int(len(real_t)),
                "missing_data_pct_vs_snapshot_calendar": missing_pct,
                "sufficient_history_for_2022_replay": bool(pd.notna(first_date) and first_date <= pd.Timestamp("2022-01-03")),
                "sufficient_history_for_2020": bool(pd.notna(first_date) and first_date <= pd.Timestamp("2020-01-01")),
                "sufficient_history_for_2015": bool(pd.notna(first_date) and first_date <= pd.Timestamp("2015-01-01")),
                "sufficient_history_for_2010": bool(pd.notna(first_date) and first_date <= pd.Timestamp("2010-01-01")),
                "sufficient_history_for_2008": bool(pd.notna(first_date) and first_date <= pd.Timestamp("2008-01-01")),
            }
        )
    out = pd.DataFrame(rows)
    out.to_csv(OUT_COVERAGE, index=False)
    return out


def reconstruction_plan(dependencies: pd.DataFrame, coverage: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    snap_start, snap_end = _source_date_range(SNAPSHOTS_FILE)
    exact_start = snap_start or ""
    approximate_start = "requires_new_historical_pipeline_run"
    price_only_start = "depends_on_downloaded_price_history_not_available_as_snapshot"
    if not coverage.empty:
        tickers_2022 = int(coverage["sufficient_history_for_2022_replay"].sum())
        tickers_2020 = int(coverage["sufficient_history_for_2020"].sum())
    else:
        tickers_2022 = 0
        tickers_2020 = 0

    rows = [
        {
            "reconstruction_type": "exact_replay",
            "earliest_possible_start_date": exact_start,
            "feasible_before_2022": False,
            "methodology": "Use stored historical_forecast_snapshots target/current price and historical_realized_returns labels.",
            "requirements": "Existing model-generated snapshots for every decision date.",
            "limitations": "Cannot start before first snapshot date.",
        },
        {
            "reconstruction_type": "approximate_replay",
            "earliest_possible_start_date": approximate_start,
            "feasible_before_2022": "possible_if_raw_prices_and_full_model_pipeline_are_rerun",
            "methodology": "Download historical prices, truncate at each t, rerun current target engine and growth feature generator, then apply soft exit/vol target/cap.",
            "requirements": "Historical adjusted close for universe, current code compatibility, no live prices, no future CEDEAR point-in-time assumption.",
            "limitations": "Not exact production parity because current code/CEDEAR list may differ from historical state.",
        },
        {
            "reconstruction_type": "price_only_replay",
            "earliest_possible_start_date": price_only_start,
            "feasible_before_2022": "partial_only",
            "methodology": "Approximate raw target with price-derived momentum/target proxy, then apply soft exit/vol targeting/cap.",
            "requirements": "Price history only.",
            "limitations": "Does not reproduce raw_target_return_exact; should be labelled a different research model.",
        },
    ]
    plan = pd.DataFrame(rows)
    plan.to_csv(OUT_PLAN, index=False)

    exact_possible = bool(exact_start and pd.Timestamp(exact_start) <= pd.Timestamp("2022-01-03"))
    governance_class = "approximate_replay_possible"
    if exact_possible and tickers_2022 > 0:
        governance_class = "exact_replay_possible_from_2022_only"
    if tickers_2020 == 0:
        pre_2022_note = "No stored model-generated snapshots before 2022-01-03; exact replay before 2022 is not feasible locally."
    else:
        pre_2022_note = "Some local data appears before 2022, but exact growth snapshots still need verification."
    governance = pd.DataFrame(
        [
            {
                "classification": governance_class,
                "exact_replay_earliest_start": exact_start,
                "approximate_replay_earliest_start": approximate_start,
                "price_only_replay_earliest_start": price_only_start,
                "requested_2008_feasible_exact": False,
                "requested_2010_feasible_exact": False,
                "requested_2015_feasible_exact": False,
                "requested_2020_feasible_exact": False,
                "production_changed": False,
                "parameter_tuning": False,
                "governance_note": pre_2022_note,
            }
        ]
    )
    governance.to_csv(OUT_GOVERNANCE, index=False)
    return plan, governance


