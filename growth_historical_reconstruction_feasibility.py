def _read_csv(path: str | Path) -> pd.DataFrame:
    p = Path(path)
    if not p.exists():
        return pd.DataFrame()
    try:
        return pd.read_csv(p)
    except Exception:
        return pd.DataFrame()


def _dates(df: pd.DataFrame, col: str = "date") -> pd.DataFrame:
    if df.empty or col not in df.columns:
        return df
    out = df.copy()
    out[col] = pd.to_datetime(out[col], errors="coerce").dt.normalize()
    return out.dropna(subset=[col]).sort_values(col)


def _num(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series, errors="coerce").replace([np.inf, -np.inf], np.nan)


def _date_minmax(df: pd.DataFrame, col: str = "date") -> tuple[pd.Timestamp | pd.NaT, pd.Timestamp | pd.NaT]:
    df = _dates(df, col)
    if df.empty:
        return pd.NaT, pd.NaT
    return df[col].min(), df[col].max()


def _source_date_range(path: str, col: str = "date") -> tuple[str, str]:
    df = _read_csv(path)
    start, end = _date_minmax(df, col)
    return (
        start.strftime("%Y-%m-%d") if pd.notna(start) else "",
        end.strftime("%Y-%m-%d") if pd.notna(end) else "",
    )


